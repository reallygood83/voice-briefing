function moveField(settings, field, map, changes) {
  const current = settings[field];
  if (typeof current !== "string" || !current)
    return;
  const next = map[current];
  if (!next || next === current)
    return;
  settings[field] = next;
  changes.push(`${String(field)}: ${current} -> ${next}`);
}
